"""Evaluate the classifier on data/sample_messages.csv and write docs/classifier_evaluation.md.

Usage:
    python scripts/evaluate_classifier.py            # uses LLM_PROVIDER from .env (default: rules)
    python scripts/evaluate_classifier.py --rules    # force the offline rules classifier

Metrics:
* accuracy           - share of messages with the right category
* precision (cat X)  - of the messages we CALLED X, how many really were X
* recall (cat X)     - of the messages that really were X, how many we found
* missed critical    - expected "critical" but predicted lower. Target: 0.
"""

from __future__ import annotations

import argparse
import csv
import sys
from collections import Counter
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))  # allow "python scripts/evaluate_classifier.py"

from app.classifier import classify_message  # noqa: E402
from app.config import Settings, get_settings  # noqa: E402
from app.taxonomy import CATEGORIES  # noqa: E402

DATA_FILE = ROOT / "data" / "sample_messages.csv"
REPORT_FILE = ROOT / "docs" / "classifier_evaluation.md"
ACCURACY_TARGET = 0.75


def load_rows(path: Path = DATA_FILE) -> list[dict]:
    with open(path, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def run_classifier(rows: list[dict], settings: Settings) -> list[dict]:
    """Add predicted_* fields to each row."""
    results = []
    for row in rows:
        r = classify_message(row["message"], settings)
        results.append({
            **row,
            "predicted_category": r.category,
            "predicted_urgency": r.urgency,
            "predicted_language": r.language,
            "method": r.method,
        })
    return results


def compute_metrics(results: list[dict]) -> dict:
    n = len(results)
    cats = list(CATEGORIES)

    def accuracy(rows, field):
        if not rows:
            return 0.0
        return sum(r[f"expected_{field}"] == r[f"predicted_{field}"] for r in rows) / len(rows)

    per_category = {}
    for c in cats:
        tp = sum(r["expected_category"] == c and r["predicted_category"] == c for r in results)
        predicted = sum(r["predicted_category"] == c for r in results)
        actual = sum(r["expected_category"] == c for r in results)
        per_category[c] = {
            "precision": tp / predicted if predicted else 0.0,
            "recall": tp / actual if actual else 0.0,
            "support": actual,
        }

    # confusion[expected][predicted] = count
    confusion = {e: Counter() for e in cats}
    for r in results:
        confusion[r["expected_category"]][r["predicted_category"]] += 1

    critical = [r for r in results if r["expected_urgency"] == "critical"]
    missed_critical = [r for r in critical if r["predicted_urgency"] != "critical"]
    # Did we notice the messages that need same-day attention?
    serious = [r for r in results if r["expected_urgency"] in ("high", "critical")]
    serious_found = [r for r in serious if r["predicted_urgency"] in ("high", "critical")]

    return {
        "n": n,
        "accuracy": accuracy(results, "category"),
        "dev_accuracy": accuracy([r for r in results if r["split"] == "dev"], "category"),
        "holdout_accuracy": accuracy([r for r in results if r["split"] == "holdout"], "category"),
        "urgency_accuracy": accuracy(results, "urgency"),
        "language_accuracy": accuracy(results, "language"),
        "per_category": per_category,
        "confusion": confusion,
        "critical_total": len(critical),
        "missed_critical": missed_critical,
        "serious_recall": len(serious_found) / len(serious) if serious else 0.0,
        "serious_total": len(serious),
        "errors": [r for r in results if r["expected_category"] != r["predicted_category"]],
        "methods": Counter(r["method"] for r in results),
    }


def render_markdown(m: dict) -> str:
    cats = list(CATEGORIES)
    passed = m["accuracy"] >= ACCURACY_TARGET and not m["missed_critical"]
    lines = [
        "# Classifier evaluation",
        "",
        f"_Generated by `scripts/evaluate_classifier.py` on {date.today().isoformat()}. "
        f"Method(s): {', '.join(f'{k} ({v})' for k, v in m['methods'].items())}._",
        "",
        f"**Result: {'PASS' if passed else 'FAIL'}** "
        f"(target: accuracy >= {ACCURACY_TARGET:.0%} and zero missed critical cases)",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Messages | {m['n']} |",
        f"| Category accuracy (all) | {m['accuracy']:.1%} |",
        f"| Category accuracy (dev, used for tuning) | {m['dev_accuracy']:.1%} |",
        f"| Category accuracy (holdout, never tuned on) | {m['holdout_accuracy']:.1%} |",
        f"| Urgency accuracy (exact level) | {m['urgency_accuracy']:.1%} |",
        f"| High/critical recall ({m['serious_total']} messages) | {m['serious_recall']:.1%} |",
        f"| Language accuracy | {m['language_accuracy']:.1%} |",
        f"| Critical cases | {m['critical_total']} |",
        f"| **Missed critical cases** | **{len(m['missed_critical'])}** |",
        "",
        "## Per-category precision and recall",
        "",
        "| Category | Precision | Recall | Support |",
        "|---|---|---|---|",
    ]
    for c in cats:
        pc = m["per_category"][c]
        lines.append(f"| {c} | {pc['precision']:.2f} | {pc['recall']:.2f} | {pc['support']} |")

    short = {c: c[:8] for c in cats}
    lines += [
        "",
        "## Confusion matrix",
        "",
        "Rows = expected category, columns = predicted category.",
        "",
        "| expected \\ predicted | " + " | ".join(short[c] for c in cats) + " |",
        "|---|" + "---|" * len(cats),
    ]
    for e in cats:
        lines.append(f"| {e} | " + " | ".join(str(m["confusion"][e][p]) for p in cats) + " |")

    lines += ["", "## Missed critical cases", ""]
    if m["missed_critical"]:
        for r in m["missed_critical"]:
            lines.append(f"- #{r['id']} predicted `{r['predicted_urgency']}`: {r['message']}")
    else:
        lines.append("None. Every critical message was flagged critical.")

    lines += ["", "## Misclassified messages (category)", "",
              "| # | Split | Expected | Predicted | Message |", "|---|---|---|---|---|"]
    for r in m["errors"]:
        msg = r["message"].replace("|", "/")
        lines.append(f"| {r['id']} | {r['split']} | {r['expected_category']} | "
                     f"{r['predicted_category']} | {msg} |")

    lines += [
        "",
        "## Honest caveats",
        "",
        "- The dataset and the keyword rules were written by the same developer, so "
        "these numbers are optimistic. The **holdout** rows (every 5th message) were "
        "never used to tune keywords and are the fairer estimate.",
        "- Most urgency errors are `low` predicted as `medium` (simple information "
        "questions). That is a harmless direction; the safety-relevant number is "
        "high/critical recall.",
        "- 150 messages is small: one message is about 0.7 percentage points.",
        "- Non-English keywords still need review by first-language speakers.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rules", action="store_true", help="force the offline rules classifier")
    args = parser.parse_args()

    settings = get_settings()
    if args.rules:
        settings = settings.model_copy(update={"llm_provider": "rules"})

    metrics = compute_metrics(run_classifier(load_rows(), settings))
    REPORT_FILE.write_text(render_markdown(metrics), encoding="utf-8")

    print(f"Accuracy:         {metrics['accuracy']:.1%} "
          f"(dev {metrics['dev_accuracy']:.1%}, holdout {metrics['holdout_accuracy']:.1%})")
    print(f"Urgency accuracy: {metrics['urgency_accuracy']:.1%} "
          f"(high/critical recall {metrics['serious_recall']:.1%})")
    print(f"Language acc.:    {metrics['language_accuracy']:.1%}")
    print(f"Missed critical:  {len(metrics['missed_critical'])} of {metrics['critical_total']}")
    print(f"Report written to {REPORT_FILE.relative_to(ROOT)}")
    ok = metrics["accuracy"] >= ACCURACY_TARGET and not metrics["missed_critical"]
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
